export const LOCALES = ['en', 'fr', 'ar'] as const;
export type Locale = (typeof LOCALES)[number];

export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, fr, ar };

/** Languages are always shown in their own name, so people can find theirs whatever is selected. */
export const LOCALE_NAMES: Record<Locale, string> = {
  en: 'English',
  fr: 'Français',
  ar: 'العربية',
};

export const isLocale = (v: unknown): v is Locale => LOCALES.includes(v as Locale);
/** The language tag used to format dates and numbers (Morocco's variant keeps Western digits). */
export const dateLocaleOf = (l: Locale): string =>
  l === 'ar' ? 'ar-MA' : l === 'fr' ? 'fr-FR' : 'en-GB';
export const dirOf = (l: Locale): 'ltr' | 'rtl' => (l === 'ar' ? 'rtl' : 'ltr');

/** Picks the first supported language from a browser language list (e.g. ["fr-MA", "en"]). */
export function detectLocale(preferred: readonly string[] | undefined): Locale {
  for (const p of preferred ?? []) {
    const base = p.toLowerCase().split('-')[0];
    if (isLocale(base)) return base;
  }
  return 'en';
}

/** Looks a message up and fills {name} placeholders. A missing translation falls back to English. */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const text = MESSAGES[locale][key] ?? en[key];
  return params
    ? text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole))
    : text;
}
